# -*- coding: utf-8 -*-
"""`oser doctor` — inspect a project's EFFECTIVE control plane and report drift.

Severity: critical (wrong truth is being served, or a dangerous default) · warning (drift that will bite)
· info (context). Exit code: 2 when any critical, 1 when any warning, else 0.

Every check is either GENERIC (works on any project) or DECLARED (driven by data the project put in its
manifest, e.g. stale markers, Firebase targets). The report labels each finding with its basis so a clean
score cannot hide behind undeclared checks.
"""
import glob
import json
import os
import re

from . import render
from .engine import CONTROL_PLANE_DOC, SETTINGS, detect_legacy
from . import ledger
from .manifest import (LOCK, MANIFEST, build_state, get, legacy_keys, load, mode_spec, ref_exists,
                       resolve_authority, root_model)
from .transcripts import observed_models
from .util import (OSER_HOME, claude_home, git, load_catalog, load_json, match_any, model_generation, plugin_version,
                   read_text, rel, sha, MODEL_RE)

SEV_ORDER = {"critical": 0, "warning": 1, "info": 2}
STATE_MAX_BYTES = 15 * 1024   # measured rule (references/3-luat-tiet-kiem.md, luật 9): 157 KB state ≈ 60k tokens/turn
BRANCH_RE = re.compile(r"\bbranch\W{0,6}`([A-Za-z0-9._/-]+)`", re.I)
PHASE_CLAIM_RE = re.compile(r"current phase", re.I)
FAMILY_CLAIM_RE = re.compile(r"\b(fable|opus|sonnet|haiku)\s+\d", re.I)   # "Opus 5" = the seat claims a tier


class Report:
    def __init__(self):
        self.findings = []
        self.facts = {}

    def add(self, sev, cid, msg, path=None, basis="generic"):
        self.findings.append({"severity": sev, "id": cid, "message": msg, "path": path, "basis": basis})

    def counts(self):
        c = {"critical": 0, "warning": 0, "info": 0}
        for f in self.findings:
            c[f["severity"]] += 1
        return c


def _current_files(root, m):
    files = ["CLAUDE.md"]
    if m:
        files.append(m["workspace"]["state_file"])
        files += (m.get("control_plane") or {}).get("current") or []
    out = []
    for f in files:
        if f not in out and os.path.isfile(os.path.join(root, f)):
            out.append(f)
    return out


def run(root, manifest_override=None):
    r = Report()
    root = os.path.abspath(root)
    version = plugin_version()
    r.facts.update({"project": root, "oser_version": version, "oser_home": OSER_HOME})
    m, errors = load(root, manifest_override)
    if m is None:
        r.add("critical", "OSR-001", "no OSER manifest (%s): project is not under NNC OSER" % MANIFEST, MANIFEST)
    for e in errors if m is not None else []:
        r.add("critical", "OSR-001", "manifest: " + e, MANIFEST)
    valid = m is not None and not errors
    if valid:
        r.facts.update({"mode": m["mode"], "phase": m["phase"]["label"]})
        _lock(r, root, m, version, manifest_override)
        _authority(r, root, m)
        _phase(r, root, m)
        _mode(r, root, m)
        _workspace(r, root, m)
        _generated(r, root, m, version)
        _firebase(r, root, m)
        _build(r, root, m)
        _ledger(r, root, m)
    _org_model(r, root, m)
    _branch_pointers(r, root, m if valid else None)
    _models(r, root, m if valid else None)
    _legacy(r, root, m if valid else None)
    _plugin(r, root, version)
    _git(r, root, (get(m, "git.main") if valid else None) or "main")
    r.findings.sort(key=lambda f: (SEV_ORDER[f["severity"]], f["id"], f["path"] or ""))
    return r


