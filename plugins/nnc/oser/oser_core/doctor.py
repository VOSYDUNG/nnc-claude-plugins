def print_report(r):
    f = r.facts
    print("NNC OSER doctor %s — %s" % (f["oser_version"], f["project"]))
    print("  mode=%s  phase=%s  lock=%s  running-from=%s" % (f.get("mode", "?"), f.get("phase", "?"),
                                                          f.get("lock_version", "(none)"), f.get("running_from", "?")))
    if "authority" in f:
        print("  authority: %s%s" % (f["authority"], ("  [local: %s]" % f["authority_local"]) if f.get("authority_local") else ""))
    rm = f.get("root_model") or {}
    print("  ROOT model  EXPECTED=%s  CONFIGURED=%s  OBSERVED=%s" % (rm.get("expected"), rm.get("configured"), rm.get("observed")))
    if "firebase" in f:
        print("  firebase: default=%s data=%s" % (f["firebase"]["default"], f["firebase"]["data_project"]))
    print("  plugin installed: %s" % (f.get("plugin_installed"),))
    for x in r.findings:
        print("  [%-8s] %s %s%s%s" % (x["severity"].upper(), x["id"], ("(%s) " % x["path"]) if x["path"] else "",
                                     x["message"], "  {declared}" if x["basis"] == "declared" else ""))
    c = r.counts()
    print("SUMMARY critical=%d warning=%d info=%d" % (c["critical"], c["warning"], c["info"]))
    return 2 if c["critical"] else 1 if c["warning"] else 0
